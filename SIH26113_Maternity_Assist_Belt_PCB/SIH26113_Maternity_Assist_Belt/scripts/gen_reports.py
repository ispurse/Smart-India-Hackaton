def gen_manufacturing_check() -> str:
    rep, drc = _json("route_report.json"), _json("drc_result.json")
    brd = _board()
    minclear = _drc_min_clearance(drc)

    drills = sorted({float(v.get("drill"))
                     for v in brd.findall("./signals/signal/via")})
    pad_drills = sorted({float(pd.get("drill"))
                         for lib in brd.findall("./libraries/library")
                         for pd in lib.findall(".//package/pad")})
    widths = sorted({float(w.get("width"))
                     for w in brd.findall("./signals/signal/wire")})

    tall = sorted(
        ((PACKAGE_HEIGHT[geom.DS[p.deviceset].package][0],
          PACKAGE_HEIGHT[geom.DS[p.deviceset].package][1], p.ref,
          geom.DS[p.deviceset].package)
         for p in D.PARTS if geom.DS[p.deviceset].package in PACKAGE_HEIGHT),
        reverse=True)

    edges = {"bottom (y < 6 mm)": [], "left (x < 6 mm)": [],
             "right (x > 94 mm)": [], "top (y > 64 mm)": [],
             "interior": []}
    for p in D.PARTS:
        if not p.ref.startswith("J"):
            continue
        if p.by < 6:
            edges["bottom (y < 6 mm)"].append(p.ref)
        elif p.bx < 6:
            edges["left (x < 6 mm)"].append(p.ref)
        elif p.bx > 94:
            edges["right (x > 94 mm)"].append(p.ref)
        elif p.by > 64:
            edges["top (y > 64 mm)"].append(p.ref)
        else:
            edges["interior"].append(p.ref)

    assy = Counter()
    HARD = {"LFCSP-20-4X4-P050", "WSON-6-DRV0006B", "LGA-14L-2.5X3.0"}
    for p in D.PARTS:
        pkg = geom.DS[p.deviceset].package
        if pkg is None:
            continue
        assy["reflow / hot air only" if pkg in HARD
             else ("reflow or hot air (castellated)"
                   if pkg == "ESP32-S3-WROOM-1" else "hand-solderable")] += 1

    L = [HEADER, "# MANUFACTURING CHECK - SIH26113 Maternity Assist Belt\n",
         "Every item the brief asks to check before declaring the design "
         "complete, with the value the files actually contain. Measured "
         "figures come from `validate_drc.py` re-reading the emitted `.brd`; "
         "assumptions are labelled as such.\n",
         "> **No fabricator capability is assumed as verified.** The numbers "
         "below are what the board *requires*. Item 7 is the one that has to "
         "be checked against a specific fab's quoted capability before "
         "ordering - see `REQUIRES_CONFIRMATION.md` H6.\n",
         "| # | Item | Value | Status |", "|---|---|---|---|",
         f"| 1 | PCB dimensions | **{D.BOARD_W:.0f} x {D.BOARD_H:.0f} mm** "
         f"({D.BOARD_W * D.BOARD_H / 100:.0f} cm2) | set in `design.py`, "
         f"outline on layer 20 |",
         f"| 2 | Board thickness | **{D.BOARD_THICKNESS} mm** FR-4 | "
         f"**assumption** - standard; dielectric split "
         f"0.36 / 0.71 / 0.36 mm declared in the rule set |",
         f"| 3 | Layer count | **{D.BOARD_LAYERS}** - "
         f"`(1*2*15*16)`; L2 = GND plane, L15 = 3V3 plane | verified in the "
         f"`.brd` design rules |",
         f"| 4 | Copper thickness | **{D.COPPER_OZ} oz (35 um)** outer and "
         f"inner | **assumption** - drives the trace-width calculation in "
         f"`POWER_BUDGET.md` |",
         f"| 5 | Via sizes | drill **{', '.join(f'{d:g}' for d in drills)} "
         f"mm**, pad 0.55-0.60 mm | {len(brd.findall('./signals/signal/via'))}"
         f" vias, all through (`extent 1-16`) |",
         f"| 6 | Minimum trace width | **{min(widths):g} mm** "
         f"(fine-pitch escapes); {', '.join(f'{w:g}' for w in widths)} mm in "
         f"use | measured from the emitted tracks |",
         f"| 7 | Minimum clearance | **{minclear} mm measured anywhere on the "
         f"board** | 0.15 mm general rule; {D.FINE_PITCH_CLEARANCE} mm inside "
         f"the 4 declared fine-pitch fan-outs. **Needs a fab quoting 5 mil / "
         f"0.127 mm** |",
         f"| 8 | Drill sizes | vias "
         f"{', '.join(f'{d:g}' for d in drills)} mm; plated pads "
         f"{', '.join(f'{d:g}' for d in pad_drills)} mm | JST PH 0.8 mm is "
         f"within JST's ø0.7 +0.1 spec; M2 holes 2.2 mm |",
         f"| 9 | Component courtyard | **no overlaps**, "
         f"{D.COURTYARD_GAP} mm minimum gap between courtyards | DRC rule D2, "
         f"enforced by the placement pass |",
         f"| 10 | Connector accessibility | "
         f"{sum(len(v) for k, v in edges.items() if k != 'interior')} of "
         f"{sum(len(v) for v in edges.values())} connectors are on a board "
         f"edge; see the table below | the "
         f"{len(edges['interior'])} interior ones all take a flying lead from "
         f"an off-board transducer |",
         f"| 11 | Antenna keep-out | **{D.ANTENNA_KEEPOUT[2] - D.ANTENNA_KEEPOUT[0]:.0f}"
         f" x {D.ANTENNA_KEEPOUT[3] - D.ANTENNA_KEEPOUT[1]:.1f} mm** at the "
         f"top edge, flush | no pad, via or track inside it (DRC rule D3); "
         f"both plane polygons are drawn as an L that omits it |",
         f"| 12 | Mounting holes | **{len(D.MOUNT_HOLES)} x M2**, 2.2 mm "
         f"drill, 4.4 mm plated annulus on GND | `H3` is at (2.6, 42) not the "
         f"top-left corner, because that corner is inside the antenna "
         f"keep-out |",
         "| 13 | Assembly feasibility | see the assembly table below | "
         "**3 parts need a stencil and reflow / hot air**; everything else is "
         "hand-solderable |",
         "| 14 | Component availability | **NOT VERIFIED** | distributor stock "
         "could not be checked from this environment. `BOM.csv` carries empty "
         "Supplier / Supplier PN / Lifecycle columns rather than invented "
         "ones |",
         "| 15 | Polarity markings | diodes and LEDs carry a silkscreen "
         "cathode bar; pad 1 = cathode on every 2-pin polarised footprint | "
         "in the library |",
         "| 16 | Pin 1 markings | silkscreen dot or chamfer on every "
         "multi-pin part; **pad 1 is square** on every through-hole connector "
         "| in the library |",
         f"| 17 | Silkscreen readability | reference designators at "
         f"0.8-1.1 mm vector text | **assumption** - most fabs hold 0.8 mm "
         f"with a 0.15 mm stroke; confirm, see `REQUIRES_CONFIRMATION.md` "
         f"L3 |",
         "| 18 | Solder-paste / stencil | **required** | order the stencil "
         "with the boards - see item 13 |",
         "| 19 | Manufacturing outputs | **NOT GENERATED** | Gerbers and "
         "drill files need Fusion's CAM processor; build guide step 19 |",
         "\n## Connector accessibility (item 10)\n",
         "| Edge | Connectors |", "|---|---|"]
    for k, v in edges.items():
        if v:
            L.append(f"| {k} | {', '.join(sorted(v))} |")
    L += ["\nThe interior connectors are the four FSR headers (`J9`-`J12`), "
          "the stretch-sensor header (`J13`) and the optional second AS5600 "
          "(`J6`). All six take a flying lead from a transducer mounted on "
          "the belt, so none of them needs a board edge - and putting the FSR "
          "headers in a vertical row inboard, rather than a long horizontal "
          "row along the edge, was deliberate: a row of through-hole pads "
          "across the board is a wall through both signal layers. See "
          "`DESIGN_ASSUMPTIONS.md` 14.\n",
          "## Assembly feasibility (item 13)\n",
          "| Method | Placements |", "|---|---|"]
    for k, v in sorted(assy.items(), key=lambda kv: -kv[1]):
        L.append(f"| {k} | {v} |")
    L += ["\nThe three parts that cannot be soldered with an iron are the "
          "**AD8232** (0.5 mm-pitch QFN with a 2.50 mm exposed pad), the "
          "**LSM6DSOX** (0.5 mm LGA) and the **TMP117** (0.65 mm WSON with a "
          "thermal pad).\n",
          "## Mechanical envelope\n",
          "No STEP geometry is attached to these footprints, so there is no "
          "solid model and **no 3D interference check has been done**. What "
          "exists instead is a height table (`PACKAGE_HEIGHT` in "
          "`lib_defs.py`) and an isometric extrusion of it in "
          "`renders/pcb_3d.png` - enough to size an enclosure and spot a "
          "connector that will foul a lid, not enough to certify clearance.\n",
          "| Height | Ref | Package | Height source |", "|---|---|---|---|"]
    seen_pkg = set()
    for h, src, ref, pkg in tall:
        if h <= 0 or pkg in seen_pkg:
            continue
        seen_pkg.add(pkg)
        L.append(f"| **{h:.2f} mm** | {ref} | `{pkg}` | {src} |")
    L += [f"\nTallest part: **{tall[0][2]} at {tall[0][0]:.1f} mm** above the "
          f"board, so the minimum internal enclosure height is about "
          f"{D.BOARD_THICKNESS + tall[0][0] + 1.5:.1f} mm including the "
          f"substrate and a little clearance.\n",
          "**Keep the battery and any metal at least 10 mm from the antenna "
          "region** (top edge, x 9-29 mm). A Li-Po pack laid against it will "
          "cost most of the radio range.\n"]
    return "\n".join(L) + "\n"


