ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "documentation"
BRD = ROOT / "pcb" / f"{LIBRARY_NAME}.brd"

HEADER = ("<!-- GENERATED by scripts/gen_reports.py from scripts/design.py "
          "plus the router and DRC output. Do not edit by hand: re-run the "
          "script. -->\n")


def _json(name: str) -> dict:
    f = ROOT / "pcb" / name
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


def _board():
    txt = BRD.read_text(encoding="utf-8")
    return ET.fromstring(txt.split("\n", 2)[2]).find("./drawing/board")


def _drc_min_clearance(drc: dict) -> str:
    for n in drc.get("notes", []):
        m = re.search(r"MINIMUM COPPER CLEARANCE ANYWHERE ON THE BOARD: "
                      r"([\d.]+) mm", n)
        if m:
            return m.group(1)
    return "see DRC_REPORT.md"


