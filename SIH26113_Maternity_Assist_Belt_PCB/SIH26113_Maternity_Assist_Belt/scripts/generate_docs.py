def gen_drc() -> str:
    body = run("validate_drc.py")
    rep = route_report()
    failed = rep.get("failed", [])
    total = rep.get("total_signal_nets", 0)
    routed = rep.get("routed", 0)
    pct = (100.0 * routed / total) if total else 0.0

    lines = [
        HEADER, "# DRC REPORT - SIH26113 Maternity Assist Belt\n",
        "## How this was produced\n",
        "`scripts/validate_drc.py` re-parses the emitted `.brd` and measures "
        "the real geometry - segment-to-segment and segment-to-pad distances, "
        "pad bounding boxes, drill sizes, board-edge and keep-out "
        "containment. It deliberately does not share code with the router, "
        "so it can contradict it.\n",
        "> **NOT EXECUTED - TOOL UNAVAILABLE:** Autodesk EAGLE / Fusion "
        "Electronics is not installed here, so *EAGLE's* DRC has not been "
        "run, and neither has its copper-pour computation. The pours in the "
        "`.brd` are declared as polygons; EAGLE calculates their actual shape "
        "when the board is opened and `RATSNEST` is executed. Running EAGLE's "
        "DRC is step 15 of PCB_BUILD_GUIDE.md.\n",
        "## Rules checked\n",
        "| # | Rule |",
        "|---|---|",
        "| D1 | every part's copper is inside the outline with edge clearance |",
        "| D2 | no two component courtyards overlap |",
        "| D3 | nothing (pad, via or track) inside the antenna keep-out |",
        "| D4 | minimum track width and minimum drill |",
        "| D5 | copper clearance, track-to-track and track-to-pad, per layer, "
        "with the declared fine-pitch exception applied by region |",
        "| D6 | routing completeness, from the router's own report |",
        "| D7 | every plane-net pad reaches its plane |",
        "| D9 | board-edge clearance for copper |",
        "\n## Stack-up as emitted\n",
        "| EAGLE layer | Role | Copper |",
        "|---|---|---|",
    ]
    for num, name, role, cu in D.STACKUP:
        lines.append(f"| {num} (`{name}`) | {role} | {cu} |")
    lines += [
        f"\nBoard outline **{D.BOARD_W:.0f} x {D.BOARD_H:.0f} mm**, "
        f"{D.BOARD_THICKNESS} mm FR-4, {D.BOARD_LAYERS} copper layers.\n",
        "\n## Clearance rules, and the one declared exception\n",
        "| Region | Min clearance | Min track |",
        "|---|---|---|",
        f"| General | **{D.GENERAL_CLEARANCE} mm** | 0.20 mm signal, "
        f"0.50 mm power |",
        f"| Inside a fine-pitch fan-out "
        f"({len(D.clearance_exceptions())} regions: AD8232, LSM6DSOX, "
        f"TMP117, HX711) | **{D.FINE_PITCH_CLEARANCE} mm** | 0.15 mm |",
        "\nThe exception is physics, not a fudge: a 0.5 mm-pitch QFN cannot "
        "be escaped at 0.15 mm / 0.15 mm - there is not enough room between "
        "the pads, which is also why the escape tracks are 0.15 mm rather "
        "than 0.20 mm. It applies only inside the named rectangles, "
        "`validate_drc.py` enforces it as such, and any pair between 0.10 "
        "and 0.15 mm inside one of them is listed as a NOTE below rather "
        "than passed silently.\n",
        "> **The board therefore needs a fabricator offering 5 mil / "
        "0.127 mm trace and gap.** That is a standard option (JLCPCB, "
        "PCBWay and most others quote it on 4-layer) but it has to be "
        "selected when ordering - see REQUIRES_CONFIRMATION.md.\n",
        "## Result\n", "```", body.rstrip(), "```",
        "\n## Routing completeness - stated plainly\n",
        f"- signal nets requiring tracks: **{total}**",
        f"- fully routed by the tool: **{routed}** ({pct:.0f}%)",
        f"- left as airwires: **{len(failed)}**",
        f"- plane nets carried by an inner pour (no tracks needed): "
        f"**{len(D.PLANE_LAYERS)}** (`GND` on layer 2, `3V3` on layer 15)",
        f"- tracks emitted: **{rep.get('wires', 0)}** segments",
        f"- vias: **{rep.get('vias', 0)}** total "
        f"({rep.get('plane_vias', 0)} plane-connect, "
        f"{rep.get('thermal_vias', 0)} thermal/exposed-pad, the rest from "
        f"routing)",
        f"- fine-pitch fan-out escapes: **{rep.get('escapes', 0)}**; "
        f"coarse-pitch radial stubs: **{rep.get('radial_stubs', 0)}**",
        f"- **clearance violations, per the independent DRC above: "
        f"see the D5 error count in the Result block - the DRC re-measures "
        f"the emitted geometry and is the authoritative number**",
        f"- the router's own tally was {rep.get('residual_violation_count', 0)}"
        f"; it uses a slightly more conservative test for which fine-pitch "
        f"region a pair falls in, so it can flag a pair the DRC clears",
        f"- measured minimum copper clearance: quoted in the D5 notes in the "
        f"Result block above - that is the figure to give the fabricator",
        f"- rip-up-and-retry attempts: **{rep.get('ripup_attempts', 0)}**; "
        f"orderings tried: **{rep.get('attempts_tried', 1)}**, "
        f"best was seed {rep.get('seed', 0)}",
    ]
    conceded = rep.get("conceded_for_clearance", [])
    if conceded:
        lines += [
            "\n### Nets deliberately left unrouted to protect clearance\n",
            "The router prioritises clearance over completeness. Where every "
            "path it could find came closer than the rule, it **rips the net "
            "out and leaves an airwire** rather than ship a tight gap. An "
            "airwire is visible in Fusion the moment the board opens and is a "
            "minute's work to route by hand; a 0.09 mm gap is invisible and "
            "might reach fabrication.\n",
            "| Net | Came within | Of | Layer |",
            "|---|---|---|---|",
        ]
        for c in conceded:
            lines.append(f"| `{c['net']}` | {c['gap_mm']:.3f} mm | "
                         f"`{c['conflicted_with']}` | {c['layer']} |")
        lines.append("")
    if failed:
        lines += [
            "\n### The airwires that remain\n",
            "These are **not** hidden. Each one appears in Fusion as an "
            "airwire the moment the board is opened, and EAGLE's own DRC will "
            "list them under \"Unrouted\". Finishing them by hand with the "
            "interactive router is step 13 of PCB_BUILD_GUIDE.md and is "
            "unlikely to take more than half an hour: every one of them is a "
            "short connection whose two ends are already fanned out.\n",
            "| Net | Terminal that could not be reached | Reported cause |",
            "|---|---|---|",
        ]
        for nm, why in failed:
            term = why.split(" unreachable")[0]
            cause = why.split("(", 1)[1].split(")")[0] if "(" in why else why
            lines.append(f"| `{nm}` | `{term}` | {cause} |")
        lines += [
            "\n**Why they are hard, and why that is a placement fact rather "
            "than a bug.** All of them terminate on a part whose pads are "
            "fanned out at 1.2-1.9 mm: the ESP32 module (36 signals escaping "
            "a 1.27 mm pitch), the AD8232 (0.5 mm QFN), the LSM6DSOX (0.5 mm "
            "LGA) and the HX711 (whose 9 plane pads each take a via right "
            "beside the pad). Those are the four most congested spots on the "
            "board and they are where a human router also spends their time.\n",
        ]
    else:
        lines.append("\nNo airwires remain: every signal net is fully "
                     "routed.\n")
    lines += [
        "\n## What has *not* been verified here\n",
        "| Item | Status |",
        "|---|---|",
        "| EAGLE/Fusion ERC | NOT EXECUTED - TOOL UNAVAILABLE |",
        "| EAGLE/Fusion DRC | NOT EXECUTED - TOOL UNAVAILABLE |",
        "| Copper-pour CONNECTIVITY | MEASURED by scripts/validate_planes.py - "
        "it punches an antipad (own radius + the declared 0.4 mm isolate) around "
        "every through-hole and via, labels the connected regions, and checks "
        "that every plane-net contact lands in the main one. Live figures: "
        "pcb/plane_result.json. This check found a real defect - two GND vias "
        "outside the pour outline, one of them C7's only path to the ground "
        "plane. See FINAL_REVIEW.md. |",
        "| Copper-pour SHAPE, exactly as EAGLE fills it | NOT COMPUTED - "
        "EAGLE calculates polygons on load. Every plane-net **pad** is given "
        "its own plane via, so pad connectivity does not depend on the pour "
        "shape. Run RATSNEST - build guide step 14. |",
        "| Gerber / drill output | NOT GENERATED - needs EAGLE's CAM processor |",
        "| 3D / mechanical interference | NOT CHECKED - no 3D models are "
        "attached to these footprints |",
        "| Impedance of the USB pair | CALCULATED - see "
        "USB_PAIR_ANALYSIS.md. As-routed ~165 ohm differential, not the "
        "90 ohm USB 2.0 asks for, because the two nets were routed as "
        "ordinary signals (0.806 mm closest gap = 2.24x the dielectric "
        "height, so they are effectively uncoupled). Not a functional "
        "risk: the ESP32-S3 USB is Full Speed only, and 44 mm at "
        "5.8 ps/mm is electrically short by 2.6x against the fastest "
        "4 ns edge USB FS permits. |",
    ]
    return "\n".join(lines) + "\n"


