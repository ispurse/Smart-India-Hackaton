def gen_gpio() -> str:
    out = [HEADER, "# GPIO ALLOCATION - ESP32-S3-WROOM-1-N8R2\n",
           "Pin numbers and alternate functions are from the "
           "*ESP32-S3-WROOM-1 & WROOM-1U Datasheet v1.8*, Table 3-1. "
           "Strapping-pin behaviour is from Section 4 / Table 4-1 of the "
           "same document.\n",
           "**Two hard constraints drove this allocation:**\n",
           "1. **ADC2 is unusable while the radio is on.** Every analog "
           "input therefore lands on ADC1, which is GPIO1-GPIO10 only. "
           "There are 8 analog signals and 10 ADC1 channels, so the budget "
           "is tight by design.\n",
           "2. **IO35/IO36/IO37 are only free on quad-PSRAM parts.** The "
           "datasheet reserves them for the Octal SPI PSRAM in the R8 and "
           "R16V variants. This board uses them, so **-N8R2 is mandatory** "
           "- do not substitute N8R8 or N16R8.\n",
           "| Module pin | Pad | Function | Net | Dir | Boot critical | ADC | "
           "Peripheral | Connected to | Notes |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for g in D.GPIO_TABLE:
        out.append(
            f"| `{g.pin}` | {g.pad} | {g.func} | `{g.net}` | {g.direction} | "
            f"{'**YES**' if g.boot_critical else 'no'} | {g.adc} | "
            f"{g.peripheral} | {g.component} | {g.notes} |"
        )

    used = [g for g in D.GPIO_TABLE if g.direction != "POWER"]
    adc1 = [g for g in D.GPIO_TABLE
            if g.adc.startswith("ADC1_") and g.direction == "ANALOG IN"]
    adc1_spare = [g for g in D.GPIO_TABLE
                  if g.adc.startswith("ADC1_")
                  and g.direction != "ANALOG IN"]
    out += [
        "\n## Budget\n",
        f"- module pins accounted for: **{len(D.GPIO_TABLE)}** "
        f"(41 physical pads; GND@1, GND@40 and the EPAD share one row)",
        f"- signal pins in use: **{len(used) - 1}** (EN plus every GPIO)",
        f"- ADC1 channels carrying analog: **{len(adc1)} of 10** "
        f"({len(adc1_spare)} more ADC1-capable pins are used digitally "
        f"or held spare: "
        + ", ".join(f"`{g.pin}`" for g in adc1_spare) + ")",
        "- ADC2 channels used for analog: **0** (deliberate - see above)",
        "- strapping pins: `IO0` (boot button), `IO3` (spare, jumper is "
        "unpopulated), `IO45` (status LED), `IO46` (alert LED). The two LEDs "
        "are wired anode-to-GPIO / cathode-to-GND through a resistor, so at "
        "reset the pin is high-impedance, the LED does not conduct, and the "
        "internal weak pull-down holds the strap at its default 0.",
        "- pin-JTAG (IO39-IO42) is given up so those four pins can carry "
        "signals; debugging uses the ESP32-S3's built-in USB-Serial-JTAG on "
        "IO19/IO20 instead.",
        "\n## Free / reserved\n",
        "Nothing is left floating. Every module pad is either driven, "
        "terminated, or brought to a test point - see ERC_REPORT.md.",
    ]
    return "\n".join(out) + "\n"


