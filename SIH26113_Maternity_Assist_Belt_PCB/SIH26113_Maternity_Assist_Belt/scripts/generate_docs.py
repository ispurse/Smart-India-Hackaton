def gen_netlist() -> str:
    rep = route_report()
    unrouted = {nm for nm, _ in rep.get("failed", [])}
    plane = set(D.PLANE_LAYERS.values())

    VOLT = {
        "GND": "0 V", "3V3": "3.3 V", "VBAT": "3.0 - 4.2 V (1S Li-Po)",
        "VBUS": "5 V (USB / charger input)",
    }
    KIND = {}
    for nm in D.NETS:
        if nm in D.POWER_NETS:
            KIND[nm] = "POWER"
        elif nm in D.ECG_NETS:
            KIND[nm] = "ANALOG (ECG)"
        elif nm.endswith("_ADC") or nm in ("VBAT_SENSE", "IO3_SPARE"):
            KIND[nm] = "ANALOG (ADC)"
        elif nm.startswith(("I2C_", "ANG_")):
            KIND[nm] = "DIGITAL I2C (bidirectional / open drain)"
        elif nm.startswith("SD_"):
            KIND[nm] = "DIGITAL SPI"
        elif nm.startswith("USB_"):
            KIND[nm] = "DIGITAL USB 2.0 FS (differential)"
        elif nm in D.MOTOR_NETS or nm.startswith(("MOTOR", "BUZZ")):
            KIND[nm] = "SWITCHED LOAD"
        else:
            KIND[nm] = "DIGITAL"

    out = [HEADER, "# NETLIST - SIH26113 Maternity Assist Belt\n",
           f"{len(D.NETS)} nets, "
           f"{sum(len(c) for c in D.NETS.values())} pin connections, "
           f"{len(D.PARTS)} parts.\n",
           "Source / destination is a design intent, not a topology claim: "
           "most of these nets are multi-drop.  \"Source\" is the pin that "
           "drives the net (a supply, an output, or an open-drain pull-up "
           "node); \"loads\" are the pins that receive it.\n",
           "| Net | Type | Voltage | Source | Loads | Routing | Notes |",
           "|---|---|---|---|---|---|---|"]

    PIN_DIR = {}
    for ds in DEVICESETS:
        for it in SYM[ds.symbol].items:
            if hasattr(it, "direction"):
                PIN_DIR[(ds.name, it.name)] = it.direction

    for nm in sorted(D.NETS):
        conns = D.NETS[nm]
        srcs, loads = [], []
        is_rail = nm in D.POWER_NETS
        for ref, pin in conns:
            p = D.PART_BY_REF[ref]
            d = PIN_DIR.get((p.deviceset, pin), "pas")
            label = f"{ref}.{pin}"
            if is_rail:
                # On a rail, only the supply markers and the regulator or
                # charger outputs drive it.  A logic output strapped to a
                # rail - LSM6DSOX SDO_AUX tied to VDDIO, for instance - is a
                # load of that rail, not its source.
                driving = d == "sup" or (ref in ("U1", "U2") and d == "out")
            else:
                driving = d in ("sup", "out", "oc")
            (srcs if driving else loads).append(label)
        if nm in plane:
            routing = f"inner plane, EAGLE layer {D.PLANE_LAYERS_INV[nm]}"
        elif nm in unrouted:
            routing = "**UNROUTED - airwire**"
        else:
            routing = "routed"
        note = ""
        if nm == "ANG2_OUT":
            note = "only used if R17 (0R, DNP) is fitted"
        if nm == "LDO_NC":
            note = "AP2112 pin 4 is No Connection - intentional"
        load_txt = ", ".join(sorted(loads)) or "-"
        if len(loads) > 14:
            load_txt = (", ".join(sorted(loads)[:14])
                        + f", ... (+{len(loads) - 14} more, {len(conns)} pins total)")
        out.append(
            f"| `{nm}` | {KIND[nm]} | {VOLT.get(nm, '3.3 V logic')} | "
            f"{', '.join(sorted(srcs)) or '-'} | {load_txt} | "
            f"{routing} | {note} |"
        )

    out.append("\n## Net fan-out summary\n")
    out.append("| Net | Pins |")
    out.append("|---|---|")
    for nm, c in sorted(D.NETS.items(), key=lambda kv: -len(kv[1]))[:12]:
        out.append(f"| `{nm}` | {len(c)} |")
    return "\n".join(out) + "\n"


