"""
generate_docs.py - Emit the generated documentation from the design model.

Everything that is derivable from the design (netlist, GPIO table, BOM,
ERC/DRC reports, statistics) is generated here rather than hand-written, so
these documents cannot drift out of step with the .sch and .brd.

Hand-written documents (README, DESIGN_ASSUMPTIONS, GROUNDING_NOTES,
COMPONENT_VERIFICATION, REQUIRES_CONFIRMATION, PCB_BUILD_GUIDE) live in
documentation/ and are maintained by hand; this script does not touch them.

Run:  python scripts/generate_docs.py
"""

from __future__ import annotations

import csv
import io
import json
import pathlib
import subprocess
import sys
from collections import Counter, defaultdict

sys.path.insert(0, str(pathlib.Path(__file__).parent))

import design as D                              # noqa: E402
import geom                                     # noqa: E402
from lib_defs import DEVICESETS, PACKAGES, SYMBOLS   # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "documentation"
DS = {d.name: d for d in DEVICESETS}
SYM = {s.name: s for s in SYMBOLS}
PKG = {p.name: p for p in PACKAGES}

HEADER = ("<!-- GENERATED by scripts/generate_docs.py from scripts/design.py. "
          "Do not edit by hand: re-run the script. -->\n")


def route_report() -> dict:
    f = ROOT / "pcb" / "route_report.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


def drc_result() -> dict:
    f = ROOT / "pcb" / "drc_result.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


def run(script: str) -> str:
    """Run a validator and capture its report text verbatim."""
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / script)],
                       capture_output=True, text=True)
    return r.stdout


