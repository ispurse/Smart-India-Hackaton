def _bom_rows():
    groups = defaultdict(list)
    for p in D.PARTS:
        ds = DS[p.deviceset]
        if ds.package is None:
            continue          # supply symbols are not physical parts
        key = (p.deviceset, p.value, p.mpn, p.manufacturer, ds.package)
        groups[key].append(p.ref)
    rows = []
    for (deviceset, value, mpn, manuf, pkg), refs in groups.items():
        refs = sorted(refs, key=lambda r: (r[0], int("".join(
            ch for ch in r if ch.isdigit()) or 0)))
        desc = DS[deviceset].description.split(".")[0]
        rows.append({
            "Reference": " ".join(refs),
            "Qty": len(refs),
            "Value": value,
            "Manufacturer": manuf or "",
            "MPN": mpn or "",
            "Description": desc,
            "Package": pkg,
            # Deliberately blank: distributor stock and lifecycle status could
            # not be checked from the environment these files were produced
            # in, and a fabricated SKU or an invented "Active" is worse than
            # an empty field.  Fill these in from your own distributor.
            "Supplier": "",
            "Supplier PN": "",
            "Lifecycle": "",
            "Library device": deviceset,
            "Notes": D.PART_BY_REF[refs[0]].desc,
        })
    rows.sort(key=lambda r: (r["Reference"][0], r["Reference"]))
    return rows


def gen_bom_csv() -> str:
    rows = _bom_rows()
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0]), lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


