def gen_stats() -> str:
    rep = route_report()
    pkg = Counter()
    for p in D.PARTS:
        ds = DS[p.deviceset]
        if ds.package:
            pkg[ds.package] += 1
    npins = sum(len(SYM[DS[p.deviceset].symbol].pin_names()) for p in D.PARTS)
    tp = [p for p in D.PARTS if p.deviceset == "TESTPOINT"]
    out = [HEADER, "# PROJECT STATISTICS\n", "| Metric | Value |", "|---|---|",
           f"| Board outline | {D.BOARD_W:.0f} x {D.BOARD_H:.0f} mm "
           f"({D.BOARD_W * D.BOARD_H / 100:.0f} cm2) |",
           f"| Copper layers | {D.BOARD_LAYERS} |",
           f"| Board thickness | {D.BOARD_THICKNESS} mm FR-4 |",
           f"| Outer copper | {D.COPPER_OZ} oz (35 um) |",
           f"| Schematic sheets | {len(D.SHEET_TITLES)} |",
           f"| Parts placed | {len([p for p in D.PARTS if DS[p.deviceset].package])} |",
           f"| Library symbols | {len(SYMBOLS)} |",
           f"| Library footprints | {len(PACKAGES)} |",
           f"| Library devices | {len(DEVICESETS)} |",
           f"| Nets | {len(D.NETS)} |",
           f"| Pin connections | {sum(len(c) for c in D.NETS.values())} |",
           f"| Symbol pins in design | {npins} |",
           f"| Test points | {len(tp)} |",
           f"| Mounting holes | {len(D.MOUNT_HOLES)} (M2) |",
           f"| Track segments | {rep.get('wires', 0)} |",
           f"| Vias | {rep.get('vias', 0)} |",
           f"| Signal nets routed | {rep.get('routed', 0)} / "
           f"{rep.get('total_signal_nets', 0)} |",
           f"| Track widths | 0.15 mm fine-pitch escapes; "
           f"{D.NET_CLASSES[0][2]:g} mm signal; {D.NET_CLASSES[1][2]:g} mm "
           f"power and motor |",
           f"| Minimum drill | 0.30 mm (vias) |",
           f"| Clearance rule | {D.GENERAL_CLEARANCE} mm general; "
           f"{D.FINE_PITCH_CLEARANCE} mm inside the fine-pitch fan-outs |",
           "\n## Placements by footprint\n", "| Footprint | Count |", "|---|---|"]
    for k, v in sorted(pkg.items(), key=lambda kv: -kv[1]):
        out.append(f"| `{k}` | {v} |")
    out += ["\n## Test points\n", "| Ref | Signal | Purpose |", "|---|---|---|"]
    for t in sorted(tp, key=lambda q: int(q.ref[2:])):
        net = next((nm for nm, c in D.NETS.items() if (t.ref, "TP") in c), "-")
        out.append(f"| {t.ref} | `{net}` | {t.desc} |")
    return "\n".join(out) + "\n"


